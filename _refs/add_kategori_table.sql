-- =======================================================
-- Tabel Master Kategori Stock (Toko Kelontong & Baju)
-- Kompatibel dengan Neon DB & Supabase (PostgreSQL)
-- =======================================================

CREATE TABLE IF NOT EXISTS public.ms_kategori (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    kode character varying(64) NOT NULL,
    nama character varying(256) NOT NULL,
    jenis_toko character varying(64) NOT NULL DEFAULT 'kelontong', -- 'kelontong', 'baju', 'umum'
    satuan_default character varying(64) NOT NULL DEFAULT 'Pcs',  -- 'Pcs', 'Kg', 'Dus', 'Pack', 'Lusin', dll.
    keterangan text,
    is_active boolean NOT NULL DEFAULT true,
    create_time timestamp without time zone DEFAULT now() NOT NULL,
    create_by character varying(256),
    update_time timestamp without time zone,
    update_by character varying(256),
    CONSTRAINT uq_ms_kategori_nama UNIQUE (nama)
);

-- Index untuk mempercepat pencarian
CREATE INDEX IF NOT EXISTS idx_ms_kategori_kode ON public.ms_kategori (kode);
CREATE INDEX IF NOT EXISTS idx_ms_kategori_jenis ON public.ms_kategori (jenis_toko);

