-- =======================================================
-- Tabel Master Barang / Produk Stock (Toko Kelontong & Baju)
-- =======================================================

CREATE TABLE IF NOT EXISTS public.ms_barang (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    barcode character varying(256) NOT NULL,
    nama character varying(256) NOT NULL,
    kategori character varying(256) NOT NULL,
    merk character varying(256),
    supplier character varying(256),
    satuan character varying(64) DEFAULT 'Pcs',
    qty integer NOT NULL DEFAULT 0,
    harga_modal integer NOT NULL DEFAULT 0,
    harga_jual integer NOT NULL DEFAULT 0,
    warna character varying(128),
    ukuran character varying(64),
    keterangan text,
    create_time timestamp without time zone DEFAULT now() NOT NULL,
    create_by character varying(256),
    update_time timestamp without time zone,
    update_by character varying(256),
    CONSTRAINT uq_ms_barang_barcode UNIQUE (barcode)
);

CREATE INDEX IF NOT EXISTS idx_ms_barang_barcode ON public.ms_barang (barcode);
CREATE INDEX IF NOT EXISTS idx_ms_barang_kategori ON public.ms_barang (kategori);
CREATE INDEX IF NOT EXISTS idx_ms_barang_nama ON public.ms_barang (nama);

